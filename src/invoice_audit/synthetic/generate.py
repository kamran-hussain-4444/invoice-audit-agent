"""Entry point for `audit generate-data`: writes the invoices, ledgers and answer_key.json.

Deterministic: the same seed always gives the same files and the same answer key.
"""

import json
import random
import shutil
from collections import defaultdict
from datetime import datetime, timedelta
from decimal import Decimal
from pathlib import Path

from invoice_audit.synthetic.entities import COMPANY, COMPANY_ADDRESS
from invoice_audit.synthetic.ledgers import write_ledgers
from invoice_audit.synthetic.render_docx import render_invoice_docx
from invoice_audit.synthetic.render_eml import build_email, covering_note, tiny_logo_png
from invoice_audit.synthetic.render_pdf import render_invoice_pdf, render_statement_pdf
from invoice_audit.synthetic.render_scan import photo_jpg, png_scan, scanned_pdf
from invoice_audit.synthetic.render_xlsx import render_invoice_xlsx
from invoice_audit.synthetic.scenarios import FY_END, FY_START, InvoiceSpec, Scenario, build_scenario
from invoice_audit.synthetic.view import build_view, format_amount, view_as_text

README = """# Synthetic engagement data

Generated by `uv run audit generate-data --seed {seed} --out {out}`. Do not edit by hand.

Fictional entities. Any resemblance to real organisations is coincidental.

- `main_sample/`: 35 invoices for Test 1 (main testing) plus 4 edge-case files
- `cutoff_sample/`: 25 invoices for Test 2 (cut-off testing)
- `ledger_fy2026.xlsx`: current-year purchase ledger ({current} lines)
- `ledger_post_ye.xlsx`: post-year-end purchase ledger ({post_ye} lines)
- `answer_key.json`: the true values, planted errors and expected test results for every invoice
"""


def truth(spec: InvoiceSpec) -> dict:
    """What a perfect extraction of this invoice would return."""
    start, end = spec.service_period or (None, None)
    if spec.period_basis == "delivery_date":
        start = end = spec.delivery_date  # the prompt's convention: goods → period is the delivery date
    return {
        "document_type": "invoice",
        "supplier_name": spec.supplier.name,
        "supplier_vat_number": spec.supplier.vat_number,
        "addressed_to": spec.addressed_to,
        "invoice_number": spec.invoice_number,
        "invoice_date": spec.invoice_date.isoformat(),
        "currency": spec.currency,
        "net_amount": str(spec.net),
        "vat_amount": str(spec.vat),
        "gross_amount": str(spec.gross),
        "description": spec.description,
        "delivery_date": spec.delivery_date.isoformat() if spec.delivery_date else None,
        "service_period_start": start.isoformat() if start else None,
        "service_period_end": end.isoformat() if end else None,
        "period_basis": spec.period_basis,
        "true_category": spec.category,
    }


def expected(spec: InvoiceSpec) -> dict:
    result = {"overall": spec.overall(), "checks": dict(spec.expected_checks)}
    if spec.test == "cutoff":
        result["recorded_in"] = spec.recorded_in
        result["suggested_adjustment"] = str(spec.expected_adjustment) if spec.expected_adjustment else None
    return result


def _render(spec: InvoiceSpec, seed: int) -> bytes:
    """The invoice file (or attachment) bytes for the spec's format."""
    pdf = render_invoice_pdf(build_view(spec), spec.layout)
    fmt = spec.format
    if fmt in ("digital_pdf", "email_pdf"):
        return pdf
    if fmt == "scanned_pdf":
        return scanned_pdf(pdf, seed)
    if fmt in ("jpg_photo", "email_jpg"):
        return photo_jpg(pdf, seed)
    if fmt == "png_scan":
        return png_scan(pdf, seed)
    if fmt == "docx":
        return render_invoice_docx(build_view(spec))
    if fmt == "xlsx":
        return render_invoice_xlsx(build_view(spec))
    raise ValueError(f"No renderer for format {fmt}")


def _write_emails(specs: list[InvoiceSpec], out: Path, seed: int) -> None:
    by_file: dict[str, list[InvoiceSpec]] = defaultdict(list)
    for spec in specs:
        if spec.format.startswith("email_"):
            by_file[spec.file].append(spec)
    for index, (file, group) in enumerate(sorted(by_file.items())):
        supplier = group[0].supplier
        numbers = [s.invoice_number for s in group]
        sent = datetime.combine(group[0].invoice_date, datetime.min.time()) + timedelta(hours=10, minutes=index)
        logo = tiny_logo_png((40 + index * 20, 80, 120)) if index % 2 == 0 else None
        if group[0].format == "email_body":
            body = "Dear accounts team,\n\nOur invoice is below. No attachment.\n\n" + view_as_text(
                build_view(group[0])
            )
            attachments = []
            subject = f"Invoice {numbers[0]} from {supplier.name}"
        else:
            body = covering_note(supplier.name, numbers)
            attachments = []
            for spec in group:
                mime = "application/pdf" if spec.format == "email_pdf" else "image/jpeg"
                attachments.append((spec.attachment, _render(spec, seed * 1000 + hash_id(spec)), mime))
            subject = f"{'Invoices' if len(numbers) > 1 else 'Invoice'} {', '.join(numbers)} - {supplier.name}"
        data = build_email("Credit Control", supplier.email, subject, body, sent, attachments,
                           message_id=f"seed{seed}-{index}", logo=logo)  # fmt: skip
        (out / file).write_bytes(data)


def hash_id(spec: InvoiceSpec) -> int:
    """A stable small number per invoice, for per-file random effects (Python's hash() varies per run)."""
    return sum(ord(ch) * (i + 1) for i, ch in enumerate(spec.invoice_id)) % 997


def _edge_cases(scenario: Scenario, out: Path, seed: int) -> list[dict]:
    rng = random.Random(seed + 99)
    folder = out / "main_sample"

    # A truncated PDF: the loader must fail it cleanly, and the run must carry on.
    sample = next(s for s in scenario.invoices if s.format == "digital_pdf")
    pdf = render_invoice_pdf(build_view(sample), sample.layout)
    (folder / "corrupt_file.pdf").write_bytes(pdf[: len(pdf) // 3])

    # A supplier statement: not an invoice, must be excluded.
    supplier = scenario.statement_supplier
    theirs = sorted((s for s in scenario.invoices if s.supplier.key == supplier.key), key=lambda s: s.invoice_date)
    rows = [(s.invoice_date.strftime("%d/%m/%Y"), s.invoice_number, "Invoice", format_amount(s.gross))
            for s in theirs]  # fmt: skip
    balance = format_amount(sum((s.gross for s in theirs), start=Decimal("0.00")))
    statement = render_statement_pdf(supplier.name, [*supplier.address, supplier.email], [COMPANY, *COMPANY_ADDRESS],
                                     rows, FY_END.strftime("%d/%m/%Y"), f"£{balance}")  # fmt: skip
    (folder / "supplier_statement.pdf").write_bytes(statement)

    # A heavily blurred photo: unreadable, must be Needs review (never guessed).
    blurry = scenario.blurry
    blurry_pdf = render_invoice_pdf(build_view(blurry), blurry.layout)
    (folder / "blurry_receipt.jpg").write_bytes(photo_jpg(blurry_pdf, seed + 7, blur=4.5))

    # A legacy Word .doc: unsupported type, must be excluded with a helpful reason.
    ole_header = bytes.fromhex("D0CF11E0A1B11AE1")
    (folder / "old_format.doc").write_bytes(ole_header + rng.randbytes(2048))

    return [
        {"file": "main_sample/corrupt_file.pdf", "expected_status": "failed", "truth": None},
        {
            "file": "main_sample/supplier_statement.pdf",
            "expected_status": "excluded",
            "truth": {"document_type": "statement", "supplier_name": supplier.name, "addressed_to": COMPANY},
        },
        {
            "file": "main_sample/blurry_receipt.jpg",
            "expected_status": "needs_review",
            "truth": truth(blurry),
            "low_confidence": ["invoice_number", "invoice_date", "amounts"],
        },
        {"file": "main_sample/old_format.doc", "expected_status": "excluded", "truth": None},
    ]


def prepare_folders(out: Path) -> None:
    for sub in ("main_sample", "cutoff_sample"):
        shutil.rmtree(out / sub, ignore_errors=True)
        (out / sub).mkdir(parents=True)


def write_invoice_files(invoices: list[InvoiceSpec], out: Path, seed: int) -> None:
    for spec in invoices:
        if not spec.format.startswith("email_"):
            (out / spec.file).write_bytes(_render(spec, seed * 1000 + hash_id(spec)))
    _write_emails(invoices, out, seed)


def write_answer_key(seed: int, invoices: list[InvoiceSpec], edge_cases: list[dict], out: Path) -> dict:
    invoices = sorted(invoices, key=lambda s: s.invoice_id)
    answer_key = {
        "seed": seed,
        "company": COMPANY,
        "fy_start": FY_START.isoformat(),
        "fy_end": FY_END.isoformat(),
        "invoices": [
            {
                "invoice_id": spec.invoice_id,
                "test": spec.test,
                "file": spec.file,
                "attachment": spec.attachment,
                "format": spec.format,
                "truth": truth(spec),
                "planted_errors": spec.planted_errors,
                "expected": expected(spec),
            }
            for spec in invoices
        ],
        "edge_cases": edge_cases,
    }
    # newline="\n" so the file is byte-identical on Windows and Linux (the generator test compares hashes)
    (out / "answer_key.json").write_text(json.dumps(answer_key, indent=2) + "\n", encoding="utf-8", newline="\n")
    return answer_key


def generate(seed: int, out: Path) -> dict:
    """Write the full synthetic engagement into `out`. Returns the answer key."""
    scenario = build_scenario(seed)
    prepare_folders(out)
    write_invoice_files(scenario.invoices, out, seed)
    edge_cases = _edge_cases(scenario, out, seed)
    current_lines, post_ye_lines = write_ledgers(scenario, out)
    answer_key = write_answer_key(seed, scenario.invoices, edge_cases, out)
    readme = README.format(seed=seed, out=out.as_posix(), current=current_lines, post_ye=post_ye_lines)
    (out / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    return answer_key
