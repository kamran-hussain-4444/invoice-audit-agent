"""`audit generate-data --scale N`: a large engagement for load testing (PLAN 15.7).

Each of the 60 hand-designed scenarios is used as a template, in turn, so the planted-error ratios stay
the same as the small data set. Every copy gets its own invoice number and file format (weighted towards
PDF, like a real inbox). Clean invoices also get new amounts and dates; planted-error copies keep their
exact figures because those figures are the error (a transposition, a 1p difference, a boundary date).
Output goes to data/scale_*/ which is gitignored.
"""

import copy
import random
from datetime import timedelta
from decimal import Decimal
from pathlib import Path

from invoice_audit.money import quantize
from invoice_audit.synthetic.generate import (
    prepare_folders,
    write_answer_key,
    write_invoice_files,
)
from invoice_audit.synthetic.ledgers import write_ledgers
from invoice_audit.synthetic.scenarios import (
    FY_END,
    FY_START,
    InvoiceSpec,
    Scenario,
    _assign_files,
    _date_in,
    _posting,
    build_scenario,
)

FORMAT_WEIGHTS = {"digital_pdf": 40, "scanned_pdf": 20, "jpg_photo": 8, "png_scan": 8, "docx": 8, "xlsx": 8,
                  "email_pdf": 8}  # fmt: skip
EXAMPLE_RUN = Path(__file__).resolve().parents[3] / "runs" / "example_fy2026.toml"

README = """# Scale test data ({n} invoices)

Generated by `uv run audit generate-data --scale {n} --seed {seed} --out {out}`. Not committed (gitignored).
Fictional entities. Any resemblance to real organisations is coincidental.

Run it:  uv run audit run --config {out}/run.toml --dry-run
"""


def _clone(template: InvoiceSpec, rng: random.Random, scenario: Scenario) -> InvoiceSpec:
    spec = copy.deepcopy(template)
    spec.format, spec.file, spec.attachment = "", "", None  # assigned afresh for the copy
    spec.invoice_number = scenario.numbering.number(spec.supplier, spec.invoice_date)
    if template.ledger_number is not None:  # the "inv 2231" vs "INV2231" control: keep the spacing difference
        spec.ledger_number = spec.invoice_number.lower().replace("inv", "inv ", 1)
    special_date = template.invoice_date in (FY_START, FY_END)
    if not template.planted_errors and spec.currency == "GBP":
        factor = Decimal(str(round(rng.uniform(0.6, 1.6), 3)))
        spec.lines = [(text, quantize(amount * factor)) for text, amount in spec.lines]
        if spec.test == "main" and not special_date:
            spec.invoice_date = _date_in(rng, FY_START, FY_END - timedelta(days=14))
            spec.posting_date = _posting(rng, spec.invoice_date)
    return spec


def generate_scale(n: int, seed: int, out: Path) -> dict:
    if n < 60:
        raise ValueError("--scale needs at least 60 invoices (one copy of every scenario)")
    base = build_scenario(seed)
    rng = random.Random(seed * 7919)
    templates = {test: [s for s in base.invoices if s.test == test] for test in ("main", "cutoff")}
    counts = {"main": round(n * 35 / 60)}
    counts["cutoff"] = n - counts["main"]

    clones: dict[str, list[InvoiceSpec]] = {}
    for test in ("main", "cutoff"):
        group = templates[test]
        clones[test] = [_clone(group[i % len(group)], rng, base) for i in range(counts[test])]

    formats = {test: rng.choices(list(FORMAT_WEIGHTS), weights=list(FORMAT_WEIGHTS.values()), k=counts[test])
               for test in ("main", "cutoff")}  # fmt: skip
    _assign_files(clones["main"], formats["main"], "main_sample", "M", rng, first_number=1, emails_before=0)
    main_emails = formats["main"].count("email_pdf")
    _assign_files(clones["cutoff"], formats["cutoff"], "cutoff_sample", "C", rng, first_number=counts["main"] + 1,
                  emails_before=main_emails)  # fmt: skip

    invoices = [*clones["main"], *clones["cutoff"]]
    scenario = Scenario(seed, invoices, None, base.statement_supplier, base.numbering, rng)
    prepare_folders(out)
    write_invoice_files(invoices, out, seed)
    write_ledgers(scenario, out, current_filler=max(100, n // 3), post_ye_filler=max(50, n // 6))
    answer_key = write_answer_key(seed, invoices, [], out)

    run_file = EXAMPLE_RUN.read_text(encoding="utf-8").replace("data/synthetic", out.as_posix())
    run_file = run_file.replace(
        "# Run settings for the synthetic engagement", f"# Run settings for the {n}-invoice scale test"
    )
    (out / "run.toml").write_text(run_file, encoding="utf-8", newline="\n")
    (out / "README.md").write_text(README.format(n=n, seed=seed, out=out.as_posix()), encoding="utf-8", newline="\n")
    return answer_key
